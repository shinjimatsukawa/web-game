async def generate():
  os.makedirs('audio/neural/praises', exist_ok=True)
  os.makedirs('audio/neural/letters', exist_ok=True)

  print(f"Total praise items to check: {len(ITEMS_100)}")
  for item_id, text in ITEMS_100:
    out = f'audio/neural/praises/{item_id}.mp3'
    if not os.path.exists(out):
      print(f"Generating praise: {item_id}")
      comm = edge_tts.Communicate(text, VOICE)
      await comm.save(out)

  print(f"Checking letters...")
  for char in ADDITIONAL_LETTERS:
    out = f'audio/neural/letters/{char}.mp3'
    if not os.path.exists(out):
      print(f"Generating letter: {char}")
      speak_text = f"{char}。" if char != 'ー' else "のばすおと。"
      comm = edge_tts.Communicate(speak_text, VOICE)
      await comm.save(out)

  print("All 100 audio files checked/generated successfully!")

if __name__ == '__main__':
  asyncio.run(generate())
